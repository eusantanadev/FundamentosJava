public class HabilidadeEspecial {

    String nomeHabilidade;
    int custoEnergia;
    boolean ativa;

    //Construtor
    public HabilidadeEspecial(String nomeHabilidade, int custoEnergia, boolean ativa){
        this.nomeHabilidade = nomeHabilidade;
        this.custoEnergia = custoEnergia;
        this.ativa = ativa;
    }
}